/**
 * lib/salary-guide-bls-states.ts: BLS OEWS wages by state for nurse
 * practitioners (29-1171), with physician assistant (29-1071) and registered
 * nurse (29-1141) medians for the comparison guides.
 *
 * WHAT IS VERIFIED, HOW AND WHEN. Every figure comes from
 * lib/salary-guide-bls-states.data.ts, which scripts/import-bls-oews-states.py
 * GENERATES from the BLS OEWS May 2025 state and national files (see that
 * module's header for the files, the filters and the checks). On 2026-11-25
 * the generator re-read all 102 state annual medians (51 NP, 51 PA) from the
 * BLS Public Data API and every one matched the file. The national NP row
 * equals STAT_SOURCES.averageSalary and its two percentiles, and the national
 * PA row equals PA_MEDIAN_WAGE in the definition guides
 * (tests/unit/salary-guide-bls-states.test.ts holds both).
 *
 * COPY RULES for every surface that prints these figures:
 *   - They are BLS estimates: "median annual wage", "10th percentile wage",
 *     each with BLS_STATE_SOURCE_LABEL or the vintage beside it. Never
 *     "average", never "earn", never a figure without its source.
 *   - The mean is stored (the extract is complete) and never rendered.
 *   - A top-coded ("#") or unpublished ("*", "**") cell is null here, with
 *     the reason in `footnote`, and renders as BLS_FOOTNOTE_LABEL. It is never
 *     printed as a number and never as 0.
 *
 * Pure data and pure functions: no Prisma, safe in any bundle.
 */
import type { StatSource } from '@/lib/stats-sources';
import {
    BLS_NATIONAL_ROWS,
    BLS_NP_FIELDS,
    BLS_NP_STATE_ROWS,
    BLS_OEWS_AS_OF,
    BLS_OEWS_REFERENCE_PERIOD,
    BLS_OEWS_STATE_FILE_URL,
    BLS_OEWS_VINTAGE,
    BLS_PA_STATE_ROWS,
    BLS_RN_STATE_ROWS,
    BLS_SHORT_FIELDS,
} from '@/lib/salary-guide-bls-states.data';

export { BLS_OEWS_AS_OF, BLS_OEWS_REFERENCE_PERIOD, BLS_OEWS_VINTAGE };

/** Why BLS printed no number for a cell. */
export type BlsFootnote = 'top-coded' | 'not-published';

/** What a page prints in place of a footnoted cell. */
export const BLS_FOOTNOTE_LABEL: Record<BlsFootnote, string> = {
    'top-coded': 'Above the BLS top code',
    'not-published': 'Not published by BLS',
};

/** One BLS cell: the number, or null with the reason BLS gave. */
export interface BlsFigure {
    /** Dollars (or a head count for employment); null for a footnoted cell. */
    readonly value: number | null;
    /** The cell as the BLS file printed it, kept so a reviewer can compare. */
    readonly raw: string;
    readonly footnote: BlsFootnote | null;
}

/** 29-1171 wages for one state or DC. */
export interface BlsStateWage {
    readonly state: string;
    readonly stateCode: string;
    /** The /salary-guide/{slug} segment, the same derivation as the route. */
    readonly slug: string;
    readonly fips: string;
    readonly employment: BlsFigure;
    readonly hourlyMedian: BlsFigure;
    readonly annualP10: BlsFigure;
    readonly annualP25: BlsFigure;
    readonly annualMedian: BlsFigure;
    readonly annualP75: BlsFigure;
    readonly annualP90: BlsFigure;
    /** Never rendered: the site publishes medians and percentiles only. */
    readonly annualMean: BlsFigure;
    /** The state's median annual wage in the StatSource shape; null when BLS published none. */
    readonly medianSource: StatSource | null;
}

/** 29-1071 or 29-1141 for one state: employment and the two medians. */
export interface BlsShortStateWage {
    readonly state: string;
    readonly stateCode: string;
    readonly slug: string;
    readonly employment: BlsFigure;
    readonly hourlyMedian: BlsFigure;
    readonly annualMedian: BlsFigure;
}

/** A national row (all three occupations carry the full field set). */
export interface BlsNationalWage {
    readonly soc: string;
    readonly occupation: string;
    readonly employment: BlsFigure;
    readonly hourlyMedian: BlsFigure;
    readonly annualP10: BlsFigure;
    readonly annualP25: BlsFigure;
    readonly annualMedian: BlsFigure;
    readonly annualP75: BlsFigure;
    readonly annualP90: BlsFigure;
    readonly annualMean: BlsFigure;
}

/** Short citation for a state NP figure, as every table caption prints it. */
export const BLS_STATE_SOURCE_LABEL = `BLS OEWS, Nurse Practitioners (29-1171), ${BLS_OEWS_REFERENCE_PERIOD}`;

/** The BLS download the state rows were read from (a permanent URL for this release). */
export const BLS_STATE_SOURCE_URL = BLS_OEWS_STATE_FILE_URL;

/**
 * Written into every StatSource built here. The URL names this release's
 * own file, so unlike /oes/current/ it cannot drift to a newer vintage.
 */
const STATE_VINTAGE_NOTE =
    'Generated by scripts/import-bls-oews-states.py from the BLS OEWS May 2025 state file, ' +
    'with every state median re-read from the BLS Public Data API on 2026-11-25. Refresh each ' +
    'spring by re-running the generator on the new release, never by editing a figure.';

/** Parse one generated cell. Exported for the tests. */
export function parseBlsCell(raw: string): BlsFigure {
    if (raw === '#') return { value: null, raw, footnote: 'top-coded' };
    if (raw === '*' || raw === '**') return { value: null, raw, footnote: 'not-published' };
    const value = Number(raw);
    if (!Number.isFinite(value) || value <= 0) {
        throw new Error(`salary-guide-bls-states: unreadable BLS cell "${raw}"`);
    }
    return { value, raw, footnote: null };
}

/** The route's slug derivation (app/salary-guide/[state]/page.tsx). */
export function stateSlugOf(stateName: string): string {
    return stateName.toLowerCase().replace(/\s+/g, '-');
}

/** "$132,300" for a dollar figure, or the footnote label; never "$0". */
export function formatBlsDollars(figure: BlsFigure): string {
    if (figure.value === null) return BLS_FOOTNOTE_LABEL[figure.footnote ?? 'not-published'];
    return `$${Math.round(figure.value).toLocaleString('en-US')}`;
}

/** "$63.61" for an hourly figure, or the footnote label. */
export function formatBlsHourly(figure: BlsFigure): string {
    if (figure.value === null) return BLS_FOOTNOTE_LABEL[figure.footnote ?? 'not-published'];
    return `$${figure.value.toFixed(2)}`;
}

/** "5,640" for an employment count, or the footnote label. */
export function formatBlsCount(figure: BlsFigure): string {
    if (figure.value === null) return BLS_FOOTNOTE_LABEL[figure.footnote ?? 'not-published'];
    return Math.round(figure.value).toLocaleString('en-US');
}

/** "$133K" for a title: whole thousands, or null when BLS published no figure. */
export function blsThousands(figure: BlsFigure): number | null {
    return figure.value === null ? null : Math.round(figure.value / 1000);
}

function npFieldIndex(field: (typeof BLS_NP_FIELDS)[number]): number {
    return 3 + BLS_NP_FIELDS.indexOf(field);
}

function shortFieldIndex(field: (typeof BLS_SHORT_FIELDS)[number]): number {
    return 3 + BLS_SHORT_FIELDS.indexOf(field);
}

function medianSourceFor(state: string, median: BlsFigure): StatSource | null {
    if (median.value === null) return null;
    return {
        value: String(median.value),
        formatted: formatBlsDollars(median),
        source: `BLS OEWS, Nurse Practitioners (29-1171), median annual wage, ${state}, ${BLS_OEWS_REFERENCE_PERIOD}`,
        sourceUrl: BLS_STATE_SOURCE_URL,
        asOf: BLS_OEWS_AS_OF,
        vintageNote: STATE_VINTAGE_NOTE,
    };
}

function toStateWage(row: readonly string[]): BlsStateWage {
    const [state, stateCode, fips] = row;
    const cell = (field: (typeof BLS_NP_FIELDS)[number]) => parseBlsCell(row[npFieldIndex(field)]);
    const annualMedian = cell('A_MEDIAN');
    return {
        state,
        stateCode,
        slug: stateSlugOf(state),
        fips,
        employment: cell('TOT_EMP'),
        hourlyMedian: cell('H_MEDIAN'),
        annualP10: cell('A_PCT10'),
        annualP25: cell('A_PCT25'),
        annualMedian,
        annualP75: cell('A_PCT75'),
        annualP90: cell('A_PCT90'),
        annualMean: cell('A_MEAN'),
        medianSource: medianSourceFor(state, annualMedian),
    };
}

function toShortWage(row: readonly string[]): BlsShortStateWage {
    const [state, stateCode] = row;
    const cell = (field: (typeof BLS_SHORT_FIELDS)[number]) => parseBlsCell(row[shortFieldIndex(field)]);
    return {
        state,
        stateCode,
        slug: stateSlugOf(state),
        employment: cell('TOT_EMP'),
        hourlyMedian: cell('H_MEDIAN'),
        annualMedian: cell('A_MEDIAN'),
    };
}

function toNational(soc: string, occupation: string, row: readonly string[]): BlsNationalWage {
    const cell = (field: (typeof BLS_NP_FIELDS)[number]) => parseBlsCell(row[BLS_NP_FIELDS.indexOf(field)]);
    return {
        soc,
        occupation,
        employment: cell('TOT_EMP'),
        hourlyMedian: cell('H_MEDIAN'),
        annualP10: cell('A_PCT10'),
        annualP25: cell('A_PCT25'),
        annualMedian: cell('A_MEDIAN'),
        annualP75: cell('A_PCT75'),
        annualP90: cell('A_PCT90'),
        annualMean: cell('A_MEAN'),
    };
}

function byState<T extends { state: string }>(rows: readonly T[]): Readonly<Record<string, T>> {
    return Object.freeze(Object.fromEntries(rows.map((row) => [row.state, row])));
}

/** 29-1171 by full state name ("District of Columbia" included): 51 entries. */
export const BLS_STATE_WAGES: Readonly<Record<string, BlsStateWage>> = byState(BLS_NP_STATE_ROWS.map(toStateWage));

/** 29-1071 by full state name: 51 entries. */
export const BLS_PA_STATE_WAGES: Readonly<Record<string, BlsShortStateWage>> = byState(BLS_PA_STATE_ROWS.map(toShortWage));

/** 29-1141 by full state name: 51 entries. */
export const BLS_RN_STATE_WAGES: Readonly<Record<string, BlsShortStateWage>> = byState(BLS_RN_STATE_ROWS.map(toShortWage));

/** National rows from the same release. */
export const BLS_NATIONAL = {
    np: toNational('29-1171', 'nurse practitioners', BLS_NATIONAL_ROWS.np),
    pa: toNational('29-1071', 'physician assistants', BLS_NATIONAL_ROWS.pa),
    rn: toNational('29-1141', 'registered nurses', BLS_NATIONAL_ROWS.rn),
} as const;

/** The state's 29-1171 row, or null for a name outside the 50 states and DC. */
export function blsStateWage(stateName: string): BlsStateWage | null {
    return BLS_STATE_WAGES[stateName] ?? null;
}

/** True when BLS published a median annual wage for NPs in the state. */
export function hasBlsStateMedian(stateName: string): boolean {
    return blsStateWage(stateName)?.annualMedian.value != null;
}

/** States with a published median, highest median first (ties by name). */
export function blsStatesByMedianDesc(): BlsStateWage[] {
    return Object.values(BLS_STATE_WAGES)
        .filter((row) => row.annualMedian.value !== null)
        .sort((a, b) => (b.annualMedian.value as number) - (a.annualMedian.value as number) || a.state.localeCompare(b.state));
}

/** The n states with the highest BLS median annual wage. */
export function topStatesByMedian(n: number): BlsStateWage[] {
    return blsStatesByMedianDesc().slice(0, Math.max(0, n));
}

/** The n states with the lowest BLS median annual wage, lowest first. */
export function bottomStatesByMedian(n: number): BlsStateWage[] {
    return blsStatesByMedianDesc().reverse().slice(0, Math.max(0, n));
}

/**
 * The state median against the national median, as a sentence fragment:
 * "8% above the national median of $132,300". Null when either is missing.
 */
export function compareWithNationalMedian(row: BlsStateWage): string | null {
    const state = row.annualMedian.value;
    const national = BLS_NATIONAL.np.annualMedian.value;
    if (state === null || national === null) return null;
    const pct = Math.round(((state - national) / national) * 100);
    const nationalLabel = formatBlsDollars(BLS_NATIONAL.np.annualMedian);
    if (pct === 0) return `in line with the national median of ${nationalLabel}`;
    return `${Math.abs(pct)}% ${pct > 0 ? 'above' : 'below'} the national median of ${nationalLabel}`;
}
