#!/usr/bin/env node
/**
 * Builds the MCP widget bundle.
 *
 *   node scripts/mcp/build-widgets.mjs          write lib/mcp/widgets/generated/bundle.ts
 *   node scripts/mcp/build-widgets.mjs --check  exit 1 if the committed bundle is stale
 *
 * The widget sources (lib/mcp/widgets/src) are browser TypeScript that the
 * server never imports, so Next's build never compiles them. esbuild bundles
 * them into one IIFE whose source is committed as a string module. Vercel
 * then needs no extra build step, and tests/lib/mcp/widget-bundle.test.ts
 * fails when someone edits a widget without rebuilding.
 *
 * Line endings are normalized before esbuild sees the sources. This tree is
 * checked out with CRLF on Windows and LF in CI, and a template literal would
 * otherwise carry \r\n into the bundle on one machine and \n on the other.
 */
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const ENTRY = path.join(ROOT, 'lib/mcp/widgets/src/main.ts');
const OUTPUT = path.join(ROOT, 'lib/mcp/widgets/generated/bundle.ts');

const normalizeLineEndings = {
  name: 'normalize-line-endings',
  setup(pluginBuild) {
    pluginBuild.onLoad({ filter: /\.ts$/ }, async (args) => ({
      contents: (await readFile(args.path, 'utf8')).replace(/\r\n/g, '\n'),
      loader: 'ts',
    }));
  },
};

export async function buildWidgetBundle() {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: ['es2019'],
    minify: true,
    legalComments: 'none',
    charset: 'utf8',
    write: false,
    logLevel: 'silent',
    plugins: [normalizeLineEndings],
  });
  return result.outputFiles[0].text.trim();
}

export function renderModule(js) {
  return [
    '// GENERATED by scripts/mcp/build-widgets.mjs from lib/mcp/widgets/src. Do not edit.',
    '// Rebuild with: node scripts/mcp/build-widgets.mjs',
    `export const WIDGET_BUNDLE_JS: string = ${JSON.stringify(js)};`,
    '',
  ].join('\n');
}

async function main() {
  const js = await buildWidgetBundle();
  const next = renderModule(js);
  if (process.argv.includes('--check')) {
    const current = await readFile(OUTPUT, 'utf8').catch(() => '');
    if (current.replace(/\r\n/g, '\n') !== next) {
      console.error('lib/mcp/widgets/generated/bundle.ts is stale. Run: node scripts/mcp/build-widgets.mjs');
      process.exit(1);
    }
    console.log('Widget bundle is up to date.');
    return;
  }
  await writeFile(OUTPUT, next, 'utf8');
  console.log(`Wrote ${path.relative(ROOT, OUTPUT)} (${(js.length / 1024).toFixed(1)} KB)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
