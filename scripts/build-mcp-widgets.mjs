/**
 * Builds the NP Hiring widget (MCP Apps view) into one self-contained HTML
 * document and writes it, as a TypeScript string, to
 * lib/mcp/widgets/generated/widget-html.ts (committed; the MCP server serves
 * it as the ui:// resource).
 *
 *   node scripts/build-mcp-widgets.mjs      (npm run build:mcp-widgets)
 *
 * buildWidgetHtml() also runs in memory: tests/mcp/widgets/build.test.ts
 * rebuilds and compares with the committed file, so a source change without
 * a rebuild fails the suite.
 *
 * The page loads nothing from the network: the bundle (Preact, the ext-apps
 * App class and its dependencies) and the stylesheet are inlined.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC_DIR = path.join(ROOT, 'lib', 'mcp', 'widgets', 'src');
const ENTRY = path.join(SRC_DIR, 'main.tsx');
const STYLES = path.join(SRC_DIR, 'styles.css');
export const OUTPUT_FILE = path.join(ROOT, 'lib', 'mcp', 'widgets', 'generated', 'widget-html.ts');

const HEADER = '// Generated by scripts/build-mcp-widgets.mjs from lib/mcp/widgets/src. Do not edit by hand.';

/**
 * Zod (pulled in by the ext-apps App class) re-exports every message locale
 * through `z.locales`, about 260 KB of the bundle. The widget never shows a
 * zod message and zod itself only applies English by default, so the locale
 * index resolves to English alone. A future zod that imports another locale
 * by name fails the build loudly instead of shipping broken.
 */
const zodEnglishOnly = {
    name: 'zod-english-locale-only',
    setup(build) {
        build.onResolve({ filter: /^\.\.\/locales\/index\.js$/ }, (args) => {
            if (!/[\\/]node_modules[\\/]zod[\\/]v4[\\/](classic|core)[\\/]/.test(args.importer)) return undefined;
            return {
                path: 'zod-locales-english',
                namespace: 'np-zod-locales',
                pluginData: { resolveDir: path.resolve(args.resolveDir, '..', 'locales') },
            };
        });
        build.onLoad({ filter: /.*/, namespace: 'np-zod-locales' }, (args) => ({
            contents: 'export { default as en } from "./en.js";',
            loader: 'js',
            resolveDir: args.pluginData.resolveDir,
        }));
    },
};

/** Keeps the inline script from closing its own element early. */
function escapeInlineScript(js) {
    if (js.includes('<!--')) {
        throw new Error('The widget bundle contains "<!--", which breaks an inline <script>. Find and rewrite the source.');
    }
    return js.replace(/<\/(script)/gi, '<\\/$1');
}

/**
 * Bundles the widget and returns the HTML document with its version (the
 * first 12 hex characters of its SHA-256), for `_meta` cache busting.
 *
 * @returns {Promise<{ html: string, version: string }>}
 */
export async function buildWidgetHtml() {
    const bundle = await esbuild.build({
        absWorkingDir: ROOT,
        entryPoints: [ENTRY],
        bundle: true,
        write: false,
        format: 'esm',
        platform: 'browser',
        target: 'es2020',
        minify: true,
        jsx: 'automatic',
        jsxImportSource: 'preact',
        define: { 'process.env.NODE_ENV': '"production"' },
        sourcemap: false,
        legalComments: 'none',
        logLevel: 'silent',
        plugins: [zodEnglishOnly],
    });
    const js = escapeInlineScript(bundle.outputFiles[0].text.trim());

    // Line endings vary by checkout (Windows working trees use CRLF); the output must not.
    const cssSource = readFileSync(STYLES, 'utf8').replace(/\r\n?/g, '\n');
    const css = (await esbuild.transform(cssSource, { loader: 'css', minify: true, legalComments: 'none' })).code.trim();
    if (/<\/style/i.test(css)) throw new Error('The widget stylesheet contains "</style".');

    const html =
        '<!doctype html><html lang="en"><head><meta charset="utf-8">' +
        '<meta name="viewport" content="width=device-width, initial-scale=1">' +
        '<meta name="color-scheme" content="light dark">' +
        `<title>NP Hiring</title><style>${css}</style></head>` +
        `<body><div id="root"></div><script type="module">${js}</script></body></html>`;
    const version = createHash('sha256').update(html).digest('hex').slice(0, 12);
    return { html, version };
}

/** The generated module's source text. */
export function renderWidgetModule({ html, version }) {
    return (
        `${HEADER}\n` +
        `export const WIDGET_HTML: string = ${JSON.stringify(html)};\n` +
        `export const WIDGET_VERSION = ${JSON.stringify(version)};\n`
    );
}

function isRunDirectly() {
    if (!process.argv[1]) return false;
    try {
        return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
    } catch {
        return false;
    }
}

if (isRunDirectly()) {
    const result = await buildWidgetHtml();
    mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
    writeFileSync(OUTPUT_FILE, renderWidgetModule(result));
    const kb = (Buffer.byteLength(result.html, 'utf8') / 1024).toFixed(1);
    process.stdout.write(`Wrote ${path.relative(ROOT, OUTPUT_FILE)} (${kb} KB, version ${result.version})\n`);
}
