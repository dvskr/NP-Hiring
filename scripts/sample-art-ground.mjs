/**
 * Samples the ground color of every illustration that ImmersiveImage or
 * CategoryHero can letterbox, plus the clay icon and navigation tiles whose
 * baked ground becomes the sticker tile face, and writes
 * lib/pseo/category-art-ground.ts.
 *
 * The color is the mean of a 4px ring around the picture's edge, so it is
 * what sits next to the picture when it is letterboxed inside a wider cell.
 * A ring mean handles soft vignettes better than one corner pixel.
 *
 * The registry (lib/pseo/category-asset-registry.ts) reads every icon and
 * nav Art.bg from the generated table, so re-run this after adding art.
 *
 * Usage: node scripts/sample-art-ground.mjs
 * Reads only public/images; touches no database.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIRS = [
  'categories/heroes', 'categories/bento', 'categories/icons', 'categories/nav',
  'job-seekers', 'employers', 'how-it-works', 'pages',
];
const RING = 4;

async function ringMean(file) {
  const { data, info } = await sharp(file).flatten({ background: '#ffffff' }).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const sum = [0, 0, 0];
  let n = 0;
  for (let y = 0; y < info.height; y++) {
    for (let x = 0; x < info.width; x++) {
      if (x >= RING && x < info.width - RING && y >= RING && y < info.height - RING) continue;
      const i = (y * info.width + x) * 3;
      sum[0] += data[i];
      sum[1] += data[i + 1];
      sum[2] += data[i + 2];
      n++;
    }
  }
  return '#' + sum.map((v) => Math.round(v / n).toString(16).padStart(2, '0')).join('');
}

const out = {};
for (const dir of DIRS) {
  const abs = path.join(ROOT, 'public', 'images', dir);
  if (!fs.existsSync(abs)) continue;
  for (const f of fs.readdirSync(abs).filter((n) => /\.(webp|png|jpg)$/i.test(n)).sort()) {
    out[`/images/${dir}/${f}`] = await ringMean(path.join(abs, f));
  }
}
const body =
  '// Generated by scripts/sample-art-ground.mjs. Do not edit by hand.\n' +
  '// Mean color of the 4px edge ring of each illustration: the color that sits\n' +
  '// beside the picture when ImmersiveImage or CategoryHero letterboxes it.\n' +
  `export const ART_GROUND: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`;
fs.writeFileSync(path.join(ROOT, 'lib', 'pseo', 'category-art-ground.ts'), body);
console.log(`sampled ${Object.keys(out).length} files`);
